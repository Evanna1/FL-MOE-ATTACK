def plot_asr(output_dir: Path) -> tuple[Path, Path]:
    """Create the vertically stacked ASR comparison figure."""
    output_dir.mkdir(parents=True, exist_ok=True)

    series = [
        ("decoder1.7", DECODER_17_ASR, "#3B82F6"),
        ("encoder1.5", ENCODER_15_ASR, "#F97316"),
        ("A3FL", A3FL_ASR, "#10B981"),
    ]

    fig, axes = plt.subplots(3, 1, figsize=(10, 9), sharex=True, sharey=True)
    for axis, (label, values, color) in zip(axes, series):
        rounds = np.arange(len(values))
        axis.plot(
            rounds,
            values,
            color=color,
            linewidth=2.2,
            marker="o",
            markersize=3.4,
            markeredgewidth=0,
        )
        axis.set_title(label, fontsize=13, fontweight="bold", loc="left")
        axis.set_ylabel("ASR")
        axis.set_xlim(0, 50)
        axis.set_ylim(0.68, 1.01)
        axis.set_xticks(np.arange(0, 51, 5))
        axis.set_yticks(np.arange(0.7, 1.01, 0.05))
        axis.grid(True, linestyle="--", linewidth=0.7, alpha=0.45)
        axis.spines["top"].set_visible(False)
        axis.spines["right"].set_visible(False)

    axes[-1].set_xlabel("Communication Round (zero-based)")
    fig.suptitle("Attack Success Rate (ASR) over Communication Rounds", fontsize=15)
    fig.tight_layout(rect=(0, 0, 1, 0.97))

    png_path = output_dir / "asr_comparison.png"
    pdf_path = output_dir / "asr_comparison.pdf"
    fig.savefig(png_path, dpi=300, bbox_inches="tight")
    fig.savefig(pdf_path, bbox_inches="tight")
    plt.close(fig)
    return png_path, pdf_path


if __name__ == "__main__":
    figure_dir = Path(__file__).resolve().parents[1] / "figures"
    png_file, pdf_file = plot_asr(figure_dir)
